#!/usr/bin/env node
// Build Mirror V's payload from the installable V workspace (v-openclaw-platform distro/workspace,
// the B line), the same content a customer install seeds, plus what only the sandbox has:
//
//   1. take distro/workspace/payload at a git ref (or a v-distro package's workspace/)
//   2. render its placeholders with the sandbox's values (WORKSPACE, AGENT_ID, STATE_DIR, TIMEZONE)
//   3. drop what the sandbox does not ship (sandbox-skip.txt, one reason per line)
//   4. add sandbox-files/ (vendored files the workspace lacks), then apply the sandbox patches in order (sandbox-patches/*.patch): the Portal's channel edge,
//      portal_schedule, memory page link, read-only Feishu, the Mirror V name. A patch that no
//      longer applies stops the import: B changed those lines and the patch needs review.
//   5. replace ../payload with the result (payload-manifest.json is regenerated by gen-manifest.mjs)
//      and record the source in ../DISTRO_WORKSPACE.json
//
// Usage:
//   node import-workspace.mjs --repo ~/v-openclaw-platform --ref origin/<branch> [--dry-run]
//   node import-workspace.mjs --dir <v-distro>/workspace [--dry-run]   (records the package's workspace commit)
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const template = path.dirname(here);

export const SANDBOX_VALUES = Object.freeze({
  WORKSPACE: "/vercel/sandbox/agent-data/workspace",
  AGENT_ID: "mirror-v-full",
  STATE_DIR: "/vercel/sandbox/agent-data/state",
  TIMEZONE: "Asia/Shanghai",
});
const PLACEHOLDER = /@@([A-Z][A-Z0-9_]*)@@/g;

const walk = (dir, base = dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p, base) : [path.relative(base, p).split(path.sep).join("/")];
});

/** Replace every @@NAME@@ in text files; an unknown or leftover placeholder is an error. */
export function render(dir, values = SANDBOX_VALUES) {
  const changed = [];
  for (const rel of walk(dir)) {
    const file = path.join(dir, rel);
    const buf = fs.readFileSync(file);
    if (buf.includes(0)) continue; // binary
    const text = buf.toString("utf8");
    if (!text.includes("@@")) continue;
    const out = text.replace(PLACEHOLDER, (all, name) => {
      if (!(name in values)) throw Error(`UNKNOWN_PLACEHOLDER:${name}:${rel}`);
      return values[name];
    });
    if (out !== text) { fs.writeFileSync(file, out); changed.push(rel); }
  }
  return changed;
}

/** sandbox-skip.txt: `<path or dir/>  # reason`; every entry must exist (stale entries are errors). */
export function readSkip(file) {
  return fs.readFileSync(file, "utf8").split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("#")).map((line) => {
    const [entry, ...why] = line.split("#");
    if (!why.join("#").trim()) throw Error(`SKIP_WITHOUT_REASON:${entry.trim()}`);
    return entry.trim();
  });
}

export function applySkip(dir, entries) {
  for (const entry of entries) {
    const p = path.join(dir, entry);
    if (!fs.existsSync(p)) throw Error(`SKIP_ENTRY_MISSING:${entry}`);
    fs.rmSync(p, { recursive: true });
  }
}

function exportPayload({ repo, ref, dir }, out) {
  if (dir) {
    fs.cpSync(dir, out, { recursive: true });
    // A v-distro package's workspace/: its manifest names the workspace commit it was built from.
    const pkg = path.join(dir, "..", "manifest.json");
    const m = fs.existsSync(pkg) ? JSON.parse(fs.readFileSync(pkg, "utf8")) : null;
    const ws = m?.schema === "v-distro/1" ? m.source?.workspace : null;
    if (!ws?.commit) return { from: "dir", dir };
    return { from: "v-distro", repo: m.source.repo, distroVersion: m.version, distroCommit: m.source.commit, ref: ws.ref, commit: ws.commit, payloadTree: ws.tree, vCoreCommit: ws.vCoreCommit };
  }
  const commit = execFileSync("git", ["-C", repo, "rev-parse", `${ref}^{commit}`], { encoding: "utf8" }).trim();
  const tree = execFileSync("git", ["-C", repo, "rev-parse", `${commit}:distro/workspace/payload`], { encoding: "utf8" }).trim();
  const core = execFileSync("git", ["-C", repo, "show", `${commit}:distro/workspace/V_CORE_COMMIT`], { encoding: "utf8" }).trim();
  const tar = execFileSync("git", ["-C", repo, "archive", commit, "distro/workspace/payload"], { maxBuffer: 1 << 30 });
  execFileSync("tar", ["-xf", "-", "-C", out, "--strip-components=3"], { input: tar });
  return { from: "git", repo: "vegekyd-sys/v-openclaw-platform", ref, commit, payloadTree: tree, vCoreCommit: core };
}

export function importWorkspace(source, { dryRun = false } = {}) {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "mirror-ws-"));
  try {
    const info = exportPayload(source, work);
    const git = (...args) => execFileSync("git", ["-C", work, ...args], { encoding: "utf8", stdio: ["pipe", "pipe", "pipe"] });
    const rendered = render(work);
    const skip = readSkip(path.join(here, "sandbox-skip.txt"));
    applySkip(work, skip);
    // Files only the sandbox has (vendored binaries the distro workspace does not carry).
    const extra = path.join(here, "sandbox-files");
    const added = fs.existsSync(extra) ? walk(extra) : [];
    for (const rel of added) if (fs.existsSync(path.join(work, rel))) throw Error(`SANDBOX_FILE_SHADOWS_WORKSPACE:${rel}`);
    if (added.length) fs.cpSync(extra, work, { recursive: true });
    git("init", "-q");
    git("add", "-A");
    git("-c", "user.name=import", "-c", "user.email=import@localhost", "commit", "-qm", "rendered");
    const patches = fs.existsSync(path.join(here, "sandbox-patches"))
      ? fs.readdirSync(path.join(here, "sandbox-patches")).filter((f) => f.endsWith(".patch")).sort() : [];
    for (const p of patches) {
      try { git("apply", "--whitespace=nowarn", path.join(here, "sandbox-patches", p)); }
      catch (e) { throw Error(`PATCH_DOES_NOT_APPLY:${p}\n${e.stderr || e.message}`); }
    }
    for (const rel of walk(work).filter((r) => !r.startsWith(".git/"))) {
      const text = fs.readFileSync(path.join(work, rel));
      if (!text.includes(0) && PLACEHOLDER.test(text.toString("utf8"))) throw Error(`PLACEHOLDER_LEFT:${rel}`);
      PLACEHOLDER.lastIndex = 0;
    }
    fs.rmSync(path.join(work, ".git"), { recursive: true });
    const record = { ...info, rendered: Object.keys(SANDBOX_VALUES), skipped: skip.length, sandboxFiles: added, patches };
    if (!dryRun) {
      const payload = path.join(template, "payload");
      const keep = new Set(["payload-manifest.json"]);
      for (const rel of walk(payload)) if (!keep.has(rel)) fs.rmSync(path.join(payload, rel));
      for (const d of fs.readdirSync(payload)) if (fs.statSync(path.join(payload, d)).isDirectory()) fs.rmSync(path.join(payload, d), { recursive: true });
      fs.cpSync(work, payload, { recursive: true });
      fs.writeFileSync(path.join(template, "DISTRO_WORKSPACE.json"), JSON.stringify(record, null, 1) + "\n");
    }
    return { ...record, files: walk(work).length, renderedFiles: rendered.length };
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const opt = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
  const source = opt("--dir") ? { dir: path.resolve(opt("--dir")) } : { repo: opt("--repo"), ref: opt("--ref") };
  if (!source.dir && !(source.repo && source.ref)) throw Error("usage: import-workspace.mjs --repo <platform> --ref <ref> | --dir <workspace>");
  console.log(JSON.stringify(importWorkspace(source, { dryRun: args.includes("--dry-run") }), null, 1));
}
